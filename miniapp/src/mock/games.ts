/** 相对时间：距今 days 天的 hour:minute（本地时区） */
function t(days: number, hour: number, minute: number): string {
  const d = new Date()
  d.setDate(d.getDate() + days)
  d.setHours(hour, minute, 0, 0)
  return d.toISOString()
}

function mkParticipant(gameId: number, userId: number, nickname: string, role: 'creator' | 'member', extra: Partial<Participant> = {}): Participant {
  return {
    id: `${gameId}-${userId}`,
    game_id: String(gameId),
    user_id: String(userId),
    nickname,
    avatar: '',
    role,
    reward_level: 1 + (userId % 5),
    total_reward_points: 60 + userId * 37,
    joined_at: t(-1, 12, 0),
    ...extra,
  }
}

